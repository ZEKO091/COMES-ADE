export function isAppLocale(value: unknown): value is AppLocale {
  return typeof value === 'string' && (APP_LOCALES as readonly string[]).includes(value);
}

export function isLanguagePreference(value: unknown): value is LanguagePreference {
  return value === 'auto' || isAppLocale(value);
}

export function currentLocale(): AppLocale {
  return activeLocale;
}

export function localeSignals(): LocaleSignals {
  return signals;
}

export function localeLabel(locale: AppLocale, inLocale: AppLocale = locale): string {
  return catalogs[inLocale][`lang.${locale}`] ?? catalogs.en[`lang.${locale}`] ?? locale;
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const template = catalogs[activeLocale][key] ?? catalogs.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function applyDomI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (key) node.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((node) => {
    const key = node.dataset.i18nTitle;
    if (key) node.title = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (key && 'placeholder' in node) (node as HTMLInputElement).placeholder = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((node) => {
    const key = node.dataset.i18nAria;
    if (key) node.setAttribute('aria-label', t(key));
  });
  document.documentElement.lang = activeLocale;
}

export function readDeviceLocale(): { tag: string; locale: AppLocale | null } {
  const tags = [...(navigator.languages ?? []), navigator.language].filter(Boolean);
  const tag = tags[0] ?? 'en';
  for (const item of tags) {
    const locale = localeFromTag(item);
    if (locale) return { tag, locale };
  }
  return { tag, locale: null };
}

export function localeFromTag(tag: string): AppLocale | null {
  const lower = tag.trim().toLowerCase().replace('_', '-');
  const primary = lower.split('-')[0] ?? '';
  if (primary === 'es' || lower.startsWith('es-')) return 'es';
  if (primary === 'pt' || lower.startsWith('pt-')) return 'pt';
  if (primary === 'fr' || lower.startsWith('fr-')) return 'fr';
  if (primary === 'de' || lower.startsWith('de-')) return 'de';
  if (primary === 'en' || lower.startsWith('en-')) return 'en';
  return null;
}

export function localeFromCountry(code: string | null | undefined): AppLocale | null {
  if (!code) return null;
  return COUNTRY_LOCALE[code.trim().toUpperCase()] ?? null;
}

export function resolveLocale(preference: LanguagePreference, next: LocaleSignals): AppLocale {
  if (preference !== 'auto') return preference;
  const device = next.deviceLocale;
  const ip = next.ipLocale;
  if (device && ip) {
    if (device === ip) return device;
    if (device === 'en' && ip !== 'en') return ip;
    return device;
  }
  return device ?? ip ?? 'en';
}

export function setActiveLocale(locale: AppLocale): boolean {
  const changed = activeLocale !== locale;
  activeLocale = locale;
  return changed;
}

export function setLocaleSignals(next: Partial<LocaleSignals>): void {
  signals = { ...signals, ...next };
}

const IP_CACHE_KEY = 'comesade.ip-locale';

type IpCache = { at: number; country: string; countryName: string; locale: AppLocale | null };

export async function detectIpLocale(): Promise<{ country: string | null; countryName: string | null; locale: AppLocale | null }> {
  try {
    const cached = readIpCache();
    if (cached) return { country: cached.country, countryName: cached.countryName, locale: cached.locale };
    const controller = new AbortController();
    const timer = window.setTimeout(() => controller.abort(), 4000);
    const response = await fetch('https://ipwho.is/', { signal: controller.signal });
    window.clearTimeout(timer);
    const data = await response.json() as { success?: boolean; country_code?: string; country?: string };
    if (!response.ok || data.success === false) return { country: null, countryName: null, locale: null };
    const country = typeof data.country_code === 'string' ? data.country_code.toUpperCase() : '';
    const countryName = typeof data.country === 'string' ? data.country : country;
    const locale = localeFromCountry(country);
    if (country) writeIpCache({ at: Date.now(), country, countryName, locale });
    return { country: country || null, countryName: countryName || null, locale };
  } catch {
    return { country: null, countryName: null, locale: null };
  }
}

function readIpCache(): IpCache | null {
  try {
    const raw = sessionStorage.getItem(IP_CACHE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as Partial<IpCache>;
    if (typeof parsed.at !== 'number' || Date.now() - parsed.at > 6 * 60 * 60 * 1000) return null;
    if (typeof parsed.country !== 'string') return null;
    return {
      at: parsed.at,
      country: parsed.country,
      countryName: typeof parsed.countryName === 'string' ? parsed.countryName : parsed.country,
      locale: isAppLocale(parsed.locale) ? parsed.locale : localeFromCountry(parsed.country),
    };
  } catch {
    return null;
  }
}

function writeIpCache(value: IpCache): void {
  try {
    sessionStorage.setItem(IP_CACHE_KEY, JSON.stringify(value));
  } catch {
    // ignore quota
  }
}
